        hub_radius         =  8.0,   # cells  shared with blade_inner_radius
        hub_height         = 12.0,   # cells  0.028 m  (taller than pitched blade span)
        pitch_angle        = 45.0,   # degrees
        num_blades         = 4,
        center             = (0.0, 0.0, 0.0),
